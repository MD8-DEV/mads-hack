"""Export one run to the repository's required outputs.

Only files the run actually produced are exported; nothing is written by hand.
File names follow the repository rules:

  phase{P}_step{M}_{prefix-}{short_name}.md                   step deliverable (latest attempt)
  phase{P}_step{M}_{prefix-}{short_name}-{artifact}.{ext}     other text artifacts of that attempt
  phase{P}_gate_{prefix-}{short_name}.md                      gate report (latest attempt)
  phase{P}_gate_{prefix-}{short_name}-attempt{N}.md           gate reports of earlier attempts
  phase{P}_gate_{prefix-}phase-review.md                      phase-exit review
  payment_test_log.md                                         MOCKED delivery test log of step 5.3

The run's decision_log.json is copied (or merged) to the requested log path.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from logbook import _atomic_write_json, validate_entries
from steps import PHASE_NAMES, STEPS
from store import RunStore, slugify

TEXT_EXTENSIONS = (".html", ".md", ".json", ".csv", ".txt")
MAX_BYTES = 60 * 1024
SKIP_ARTIFACTS = ("deliverable.md", "deliverable.json", "gate_report.md")
OUTPUT_NAME = re.compile(r"^phase\d_(step\d+|gate)_[a-z0-9-]+\.(md|json|html|csv|txt)$")
PAYMENT_LOG = "payment_test_log.md"
_CONTRACT = re.compile(r"^contract_v(\d+)\.json$")
_ATTEMPT_DIR = re.compile(r"^attempt(\d+)$")


def is_output_name(name: str) -> bool:
    """True for a file name this exporter may write (used by tests and by the demo clean-up)."""
    return bool(OUTPUT_NAME.match(name)) or name == PAYMENT_LOG


def _prefix(prefix: str) -> str:
    slug = slugify(prefix, max_len=30) if prefix else ""
    return f"{slug}-" if slug else ""


def _flatten(artifact_name: str) -> tuple[str, str]:
    """'product/index.html' -> ('product-index', '.html')."""
    path = Path(artifact_name.replace("\\", "/"))
    ext = path.suffix.lower()
    stem = str(path.with_suffix("")).replace("\\", "/")
    return slugify(stem.replace("/", "-").replace("_", "-"), max_len=60), ext


def _write(path: Path, text: str, written: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    written.append(str(path))


def _read(store: RunStore, run_id: str, rel: str) -> str | None:
    path = store.artifact_path(run_id, rel)
    if not path.is_file():
        return None
    if path.stat().st_size > MAX_BYTES:
        return None
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _attempt_of(rel: str) -> int | None:
    for part in rel.replace("\\", "/").split("/"):
        match = _ATTEMPT_DIR.match(part)
        if match:
            return int(match.group(1))
    return None


def render_phase_review(run, phase: int) -> str:
    review = run.phase_reviews.get(str(phase)) or {}
    summary = review.get("summary") or {}
    lines = [f"# Phase {phase} exit review: {PHASE_NAMES.get(phase, '')}", "",
             f"Venture: **{run.title}** | Run `{run.run_id}` | Opened {review.get('opened_at') or 'n/a'}", ""]
    if isinstance(summary, dict) and summary.get("summary"):
        lines += ["## Phase summary (generated by the gatekeeper agent)", "", str(summary["summary"]), ""]
        for key, label in (("confirmed", "Assumptions confirmed"), ("killed", "Assumptions killed"),
                           ("open", "Still open")):
            items = summary.get(key) or []
            if items:
                lines += [f"**{label}:**", ""] + [f"- {item}" for item in items] + [""]
    steps = review.get("steps") or []
    if steps:
        lines += ["## Step outcomes", "", "| Step | Name | Outcome | Founder override |", "|---|---|---|---|"]
        for s in steps:
            lines.append(f"| {s.get('step')} | {s.get('name')} | {s.get('outcome') or 'pending'} | "
                         f"{'yes' if s.get('overridden') else 'no'} |")
        lines.append("")
    lines += ["## Founder answers", ""]
    if review.get("answered_at"):
        match = review.get("match")
        confidence = review.get("confidence")
        lines += ["| Question | Answer |", "|---|---|",
                  f"| Do these deliverables match what you need? | {match} |",
                  f"| Is anything unclear, missing or wrong? | {(review.get('issues') or 'none').replace('|', '/')} |",
                  f"| Confidence to proceed (1-5) | {confidence} |", "",
                  f"Answered {review.get('answered_at')} via {review.get('channel') or 'n/a'}.", ""]
        rubric = review.get("rubric") or {}
        if rubric.get("total") is not None:
            lines += [f"Founder Answer Rubric on the issues text: {rubric.get('total')}/8 ({rubric.get('decision')}).", ""]
        proceed = match == "Yes" and isinstance(confidence, int) and confidence > 2
        lines += ["**Result:** " + ("the founder confirmed the phase; the pipeline moves to the next phase."
                                    if proceed else
                                    "the founder did not confirm the phase; the named step is repeated."), ""]
    else:
        lines += ["_Not answered yet: the pipeline waits for the founder's three answers._", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_override(meta, st) -> str:
    decision = st.decision or {}
    chosen = decision.get("chosen")
    lines = [f"GATE NOT EVALUATED: step {meta.step_id} {meta.name}. Founder chose {chosen} without gate data "
             "(FOUNDER_OVERRIDE; this never counts as a passed evidence gate).", "",
             "| Field | Value |", "|---|---|",
             f"| Phase / Step | {meta.step_id} {meta.name} (Phase {meta.phase}: {meta.phase_name}) |",
             f"| Gate type(s) | {' + '.join(meta.gate_types)} |",
             f"| Recommended outcome | {decision.get('recommended') or 'none (no data, gate not evaluable)'} |",
             f"| Founder's outcome | {chosen} |",
             f"| Reason | {str(decision.get('reason') or '').replace('|', '/')} |",
             f"| Channel | {decision.get('channel')} |",
             f"| Decided at | {decision.get('at')} |"]
    if st.contract:
        criteria = "; ".join(f"{c.get('key')} {c.get('op')} {c.get('target')}" for c in st.contract.get("criteria") or [])
        lines.append(f"| Locked thresholds (untested) | {criteria} (v{st.contract.get('version')}) |")
    return "\n".join(lines) + "\n"


def _export_log(store: RunStore, run_id: str, log_path: Path, append: bool, written: list[str]) -> None:
    source = store.path(run_id) / "decision_log.json"
    entries: list[dict[str, Any]] = json.loads(source.read_text(encoding="utf-8") or "[]") if source.exists() else []
    if append and log_path.exists():
        existing = json.loads(log_path.read_text(encoding="utf-8") or "[]")
        seen = {(e.get("run_id"), e.get("log_id")) for e in existing}
        merged = list(existing) + [e for e in entries if (e.get("run_id"), e.get("log_id")) not in seen]
        entries = sorted(merged, key=lambda e: str(e.get("timestamp") or ""))
    problems = validate_entries(entries)
    if problems:
        raise ValueError("decision log does not validate: " + "; ".join(problems[:5]))
    _atomic_write_json(log_path, entries)
    written.append(str(log_path))


def export_run(store: RunStore, run_id: str, out_dir: Path | str, prefix: str = "", *,
               log_path: Path | str | None = None, append_log: bool = False) -> list[str]:
    """Write the run's deliverables, gate reports and phase reviews to out_dir. Returns the written paths."""
    run = store.load(run_id)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    pfx = _prefix(prefix)
    written: list[str] = []
    run_dir = store.path(run_id)

    for meta in STEPS:
        st = run.steps.get(meta.step_id)
        if st is None or not st.artifacts:
            continue
        minor = meta.step_id.split(".")[1]
        base = f"phase{meta.phase}_step{minor}_{pfx}{meta.short_name}"

        deliverable = st.artifacts.get("deliverable.md")
        if deliverable:
            text = _read(store, run_id, deliverable)
            if text is not None:
                _write(out / f"{base}.md", text, written)

        # Latest contract only (the locked thresholds this attempt was judged against).
        if st.contract:
            version = int(st.contract.get("version") or 1)
            _write(out / f"{base}-contract-v{version}.json",
                   json.dumps(st.contract, indent=2, ensure_ascii=False) + "\n", written)
        else:
            contracts = {int(m.group(1)): rel for name, rel in st.artifacts.items() if (m := _CONTRACT.match(name))}
            if contracts:
                latest = max(contracts)
                text = _read(store, run_id, contracts[latest])
                if text is not None:
                    _write(out / f"{base}-contract-v{latest}.json", text, written)

        for name, rel in sorted(st.artifacts.items()):
            if name in SKIP_ARTIFACTS or _CONTRACT.match(name):
                continue
            stem, ext = _flatten(name)
            if ext not in TEXT_EXTENSIONS or not stem:
                continue
            text = _read(store, run_id, rel)
            if text is None:
                continue
            _write(out / f"{base}-{stem}{ext}", text, written)
            if meta.step_id == "5.3" and Path(name).name == PAYMENT_LOG:
                _write(out / PAYMENT_LOG, text, written)

        # Gate reports: latest attempt, then earlier attempts.
        gate_base = f"phase{meta.phase}_gate_{pfx}{meta.short_name}"
        latest_rel = st.artifacts.get("gate_report.md")
        if latest_rel:
            text = _read(store, run_id, latest_rel)
            if text is not None:
                _write(out / f"{gate_base}.md", text, written)
        elif st.decision and st.decision.get("override"):
            # The founder chose an outcome without an evaluated gate: export that record, never a made-up result.
            _write(out / f"{gate_base}.md", render_override(meta, st), written)
        latest_attempt = _attempt_of(latest_rel) if latest_rel else None
        step_dir = run_dir / "artifacts" / f"step{meta.step_id.replace('.', '_')}"
        if step_dir.is_dir():
            for attempt_dir in sorted(step_dir.iterdir()):
                match = _ATTEMPT_DIR.match(attempt_dir.name)
                report = attempt_dir / "gate_report.md"
                if not match or not report.is_file() or int(match.group(1)) == latest_attempt:
                    continue
                text = _read(store, run_id, str(report.relative_to(run_dir)))
                if text is not None:
                    _write(out / f"{gate_base}-attempt{int(match.group(1))}.md", text, written)

    for phase_key in sorted(run.phase_reviews, key=lambda k: int(k)):
        _write(out / f"phase{int(phase_key)}_gate_{pfx}phase-review.md", render_phase_review(run, int(phase_key)),
               written)

    if log_path is not None:
        _export_log(store, run_id, Path(log_path), append_log, written)
    return written


def merge_logs(store: RunStore, run_ids: list[str], log_path: Path | str) -> int:
    """Write the merged decision log of several runs (sorted by timestamp). Returns the entry count."""
    entries: list[dict[str, Any]] = []
    for run_id in run_ids:
        source = store.path(run_id) / "decision_log.json"
        if source.exists():
            entries += json.loads(source.read_text(encoding="utf-8") or "[]")
    entries.sort(key=lambda e: str(e.get("timestamp") or ""))
    problems = validate_entries(entries)
    if problems:
        raise ValueError("decision log does not validate: " + "; ".join(problems[:5]))
    _atomic_write_json(Path(log_path), entries)
    return len(entries)
